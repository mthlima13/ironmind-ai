/**
 * Trivial, non reversible hash.
 *
 * The mock backend has no security boundary; it is only used to fingerprint
 * requests of the same idempotency key.
 */
function mockHash(value: string): string {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return `mock$${(hash >>> 0).toString(16)}`;
}

function isCanonicalUuid(value: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(
    value
  );
}

/**
 * Everything owned by one identity. The map of scopes is the data store of
 * the mock: two identities never see each other's records (AUTH-INTEGRATION
 * test B5, enforced here as well).
 */
type UserScope = {
  restrictions: InjuryRestriction[];
  sessions: WorkoutSession[];
  programs: WorkoutProgram[];
  customExercises: Exercise[];
  /** Recommendations generated by the mock AI and their review state. */
  recommendations: Map<
    string,
    { status: RecommendationStatus; savedProgramId: string | null }
  >;
  /** Idempotency key -> request fingerprint and the created response. */
  idempotency: Map<string, { fingerprint: string; response: unknown }>;
  sequence: number;
};

type MockState = {
  scopes: Map<string, UserScope>;
};

type RouteContext = {
  params: Record<string, string>;
  query: URLSearchParams;
  body: Record<string, unknown>;
  headers: Record<string, string>;
  /** Identity of the request, or `null` on anonymous public calls. */
  identity: string | null;
  path: string;
};

type MockRoute = {
  method: string;
  pattern: RegExp;
  paramNames: string[];
  requiresIdentity: boolean;
  handler: (context: RouteContext) => unknown;
};

const MOCK_RESPONSE_FLAG = '__mockResponse';

/** Response of a route that does not answer with `200 OK`. */
type MockHandlerResult = {
  [MOCK_RESPONSE_FLAG]: true;
  status: number;
  data: unknown;
};

function respond(status: number, data: unknown): MockHandlerResult {
  return { [MOCK_RESPONSE_FLAG]: true, status, data };
}

function isHandlerResult(value: unknown): value is MockHandlerResult {
  return (
    typeof value === 'object' &&
    value !== null &&
    (value as MockHandlerResult)[MOCK_RESPONSE_FLAG] === true
  );
}

function createState(): MockState {
  return { scopes: new Map<string, UserScope>() };
}

/** Returns the data store of an identity, creating an empty one on demand. */
function scopeOf(state: MockState, identity: string): UserScope {
  const existing = state.scopes.get(identity);
  if (existing) {
    return existing;
  }
  const created: UserScope = {
    restrictions: [],
    sessions: [],
    programs: [],
    customExercises: [],
    recommendations: new Map(),
    idempotency: new Map<string, { fingerprint: string; response: unknown }>(),
    sequence: 0,
  };
  state.scopes.set(identity, created);
  return created;
}

function nextId(scope: UserScope, prefix: string): string {
  scope.sequence += 1;
  return `${prefix}-${scope.sequence}`;
}

/** Catalogue visible to one identity: the system one plus personal exercises. */
function exerciseCatalogue(scope: UserScope): Exercise[] {
  return [...MOCK_EXERCISES, ...scope.customExercises];
}

function findExercise(scope: UserScope, id: string): Exercise | undefined {
  return exerciseCatalogue(scope).find((item) => item.id === id);
}

/** Finds a set across the sessions of the user, with its session and exercise. */
function findSessionSet(scope: UserScope, setId: string):
  | {
      session: WorkoutSession;
      sessionExercise: SessionExercise;
      set: ExerciseSet;
    }
  | undefined {
  for (const session of scope.sessions) {
    for (const sessionExercise of session.exercises) {
      const set = sessionExercise.sets.find((item) => item.id === setId);
      if (set) {
        return { session, sessionExercise, set };
      }
    }
  }
  return undefined;
}

function errorBody(
  status: number,
  code: ApiErrorCode,
  message: string,
  path: string,
  fieldErrors?: FieldError[]
): ApiErrorResponse {
  return {
    timestamp: new Date().toISOString(),
    status,
    error: STATUS_TEXT[status] ?? 'Error',
    code,
    message,
    path,
    traceId: `mock-${Math.random().toString(16).slice(2, 10)}`,
    ...(fieldErrors ? { fieldErrors } : {}),
  };
}

function fail(
  status: number,
  code: ApiErrorCode,
  message: string,
  path: string,
  fieldErrors?: FieldError[]
): never {
  throw new MockHttpError(status, errorBody(status, code, message, path, fieldErrors));
}

class MockHttpError extends Error {
  readonly status: number;

  readonly body: ApiErrorResponse;

  constructor(status: number, body: ApiErrorResponse) {
    super(body.message);
    this.name = 'MockHttpError';
    this.status = status;
    this.body = body;
  }
}

function paginate<T>(items: T[], page: number, size: number): Page<T> {
  const safeSize = Math.min(Math.max(size, 1), 100);
  const safePage = Math.max(page, 0);
  const start = safePage * safeSize;
  const content = items.slice(start, start + safeSize);
  const totalElements = items.length;
  const totalPages = Math.ceil(totalElements / safeSize);
  return {
    content,
    page: safePage,
    size: safeSize,
    totalElements,
    totalPages,
    hasNext: safePage + 1 < totalPages,
  };
}

function buildRoute(
  method: string,
  path: string,
  requiresIdentity: boolean,
  handler: (context: RouteContext) => unknown
): MockRoute {
  const paramNames: string[] = [];
  const pattern = path.replace(/:([A-Za-z0-9_]+)/g, (_match, name: string) => {
    paramNames.push(name);
    return '([^/]+)';
  });
  return {
    method,
    pattern: new RegExp(`^${pattern}$`),
    paramNames,
    requiresIdentity,
    handler,
  };
}

