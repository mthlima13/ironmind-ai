/**
 * In-memory implementation of the IronFit AI API contract.
 *
 * The app ships with this adapter so every screen can be exercised without a
 * running backend. It follows the SPEC contracts: paginated envelopes
 * (A.2), the single error format (A.1), the identity header of the delegated
 * authentication (A.4) and idempotent writes (A.3).
 *
 * The ownership follows the identity header exactly like the backend: every
 * private resource is read and written inside the scope of the UUID received
 * on `X-User-UUID`, and a missing or malformed identity answers `401`
 * before any business rule. A brand new identity sees only empty data
 * (SPEC 6.4) — there is no seeded account.
 */
